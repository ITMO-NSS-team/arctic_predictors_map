// Широта, по которой обрезана подложка. Это широта углов расчётной сетки
// EASE2 432x432 (docs/DATASET.md): карта покрывает ровно область данных.
// Значение продублировано в tools/prepare_basemap.py -- менять надо оба
// и заново прогонять подготовку, иначе геометрия не совпадёт с кругом карты.
export const MIN_LAT = 16.6;

// Широта, до которой видно при стартовом зуме по короткой стороне окна.
// 52 -- Арктика с узким поясом средних широт: видны Скандинавия, Аляска,
// Охотское море, но не Средиземное и не Китай.
export const INITIAL_LAT = 52;

// 512 вместо стандартных 256: тайлы рисуются вектором на лету, и крупный
// тайл выгоднее -- меньше повторного обхода геометрии на кадр.
export const TILE = 512;

// Проекция отображения. lon_0 = 0 фиксирован: вращение делает не proj4,
// а наш собственный поворот плоскости (src/crs.js), иначе пришлось бы
// пересоздавать CRS на каждый кадр.
//
// lat_ts = 70 -- широта истинного масштаба, как в EPSG:3413 (NSIDC Sea Ice
// Polar Stereographic North). На ней искажения нулевые, и стандартные
// ледовые продукты меряются в той же метрике.
export const DISPLAY_PROJ =
  '+proj=stere +lat_0=90 +lat_ts=70 +lon_0=0 +k=1 +x_0=0 +y_0=0 ' +
  '+datum=WGS84 +units=m +no_defs';

// Проекция расчётной сетки: EASE-Grid 2.0 North, EPSG:6931.
// Нужна для наложения полей данных (src/field.js).
export const DATA_PROJ =
  '+proj=laea +lat_0=90 +lon_0=0 +x_0=0 +y_0=0 ' +
  '+datum=WGS84 +units=m +no_defs';

// Сетка OSISAF NH EASE2 25 км: 432x432, квадрат 10775x10775 км с полюсом
// в центре. Половина стороны в метрах.
export const DATA_GRID = {
  size: 432,
  halfExtent: 5387500,
  get cellSize() { return 2 * this.halfExtent / this.size; },
};

// Меридиан, направленный вверх при старте. 180 -- компоновка, привычная по
// ледовым картам: Гринвич внизу, Берингов пролив сверху, Гренландия слева.
export const INITIAL_LON_UP = 180;


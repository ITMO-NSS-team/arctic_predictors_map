// Палитра и толщины линий.
//
// Ориентир -- бумажная картография National Geographic: тёплая кремовая
// суша, холодный десатурированный океан ступенями по глубине, тонкие
// холодно-серые берега, подписи с засечками. Главное правило, которое
// делает такую карту «красивой»: почти нет насыщенных цветов, весь контраст
